  'الثامن', 'التاسع', 'العاشر', 'الحادي عشر', 'الثاني عشر', 'الثالث عشر',
  'الرابع عشر', 'الخامس عشر', 'السادس عشر', 'السابع عشر', 'الثامن عشر',
  'التاسع عشر', 'العشرون',
];

/// الترتيب بالحروف حتى 20، وما بعده يُكتب رقماً.
String ordinalAr(int n) => (n >= 1 && n < _ordinals.length) ? _ordinals[n] : '$n';
