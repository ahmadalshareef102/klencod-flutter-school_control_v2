/// تفقيط الأعداد والترتيب بالحروف (للشهادات).
const _units = ['', 'واحدة', 'اثنتان', 'ثلاث', 'أربع', 'خمس', 'ست', 'سبع', 'ثماني', 'تسع'];
const _unitsM = ['صفر', 'واحد', 'اثنان', 'ثلاثة', 'أربعة', 'خمسة', 'ستة', 'سبعة', 'ثمانية', 'تسعة'];
const _teens = {
  10: 'عشر', 11: 'إحدى عشرة', 12: 'اثنتا عشرة', 13: 'ثلاث عشرة',
  14: 'أربع عشرة', 15: 'خمس عشرة', 16: 'ست عشرة', 17: 'سبع عشرة',
  18: 'ثماني عشرة', 19: 'تسع عشرة',
};
const _tens = {
  20: 'عشرون', 30: 'ثلاثون', 40: 'أربعون', 50: 'خمسون',
  60: 'ستون', 70: 'سبعون', 80: 'ثمانون', 90: 'تسعون',
};
const _hundreds = {
  1: 'مائة', 2: 'مائتان', 3: 'ثلاثمائة', 4: 'أربعمائة', 5: 'خمسمائة',
  6: 'ستمائة', 7: 'سبعمائة', 8: 'ثمانمائة', 9: 'تسعمائة',
};
const _thousands = {
  1: 'ألف', 2: 'ألفان', 3: 'ثلاثة آلاف', 4: 'أربعة آلاف', 5: 'خمسة آلاف',
  6: 'ستة آلاف', 7: 'سبعة آلاف', 8: 'ثمانية آلاف', 9: 'تسعة آلاف',
};

String _below100(int r) {
  if (r < 10) return _units[r];
  if (r < 20) return _teens[r]!;
  final t = r ~/ 10 * 10, u = r % 10;
  return u == 0 ? _tens[t]! : '${_units[u]} و${_tens[t]}';
}

String _below1000(int n) {
  final h = n ~/ 100, r = n % 100;
  final parts = <String>[
    if (h > 0) _hundreds[h]!,
    if (r > 0) _below100(r),
  ];
  return parts.join(' و');
}

String _intWords(int n) {
  if (n == 0) return 'صفر';
  final th = n ~/ 1000, rest = n % 1000;
  final parts = <String>[];
  if (th > 0) {
    parts.add(th < 10 ? _thousands[th]! : '${_below1000(th)} ألف');
  }
  if (rest > 0) parts.add(_below1000(rest));
  return parts.join(' و');
}

/// 435 → «أربعمائة وخمس وثلاثون»، و96.5 → «ست وتسعون ونصف».
String arabicWords(num value) {
  final n = value.floor();
  var w = _intWords(n);
  final frac = ((value - n) * 10).round();
  if (frac == 5) {
    w += ' ونصف';
  } else if (frac > 0 && frac < 10) {
    w += ' فاصلة ${_unitsM[frac]}';
  }
  return w;
}

